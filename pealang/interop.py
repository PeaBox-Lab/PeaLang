"""Interoperability helpers for using PeaLang with other languages.

The helpers are intentionally dependency-light and favor explicit, auditable
boundaries: Python modules are imported by name, native libraries are loaded
through ctypes, and other runtimes are reached through HTTP or command-line
interfaces.
"""

from __future__ import annotations

import ctypes
import importlib
import json
import subprocess
import sys
import urllib.request
from pathlib import Path
from typing import Any


def call_python(module: str, function: str, *args: Any, kwargs: dict[str, Any] | None = None) -> Any:
    mod = importlib.import_module(str(module))
    fn = getattr(mod, str(function))
    return fn(*args, **(kwargs or {}))


def import_python(module: str) -> Any:
    return importlib.import_module(str(module))


def which(command: str) -> str | None:
    import shutil
    return shutil.which(str(command))


def python_module_available(module: str) -> bool:
    try:
        importlib.import_module(str(module))
        return True
    except Exception:
        return False


def run_command(command: str | list[str], args: list[str] | None = None, cwd: str | None = None,
               timeout: int = 30, env: dict[str, str] | None = None) -> dict[str, Any]:
    if isinstance(command, str):
        cmd = [command] + list(args or [])
    else:
        cmd = list(command) + list(args or [])
    try:
        proc = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=timeout, env=env, check=False)
        return {
            "ok": proc.returncode == 0,
            "returncode": proc.returncode,
            "stdout": proc.stdout,
            "stderr": proc.stderr,
            "command": cmd,
        }
    except FileNotFoundError as exc:
        return {"ok": False, "returncode": 127, "stdout": "", "stderr": str(exc), "command": cmd}
    except subprocess.TimeoutExpired as exc:
        return {"ok": False, "returncode": 124, "stdout": exc.stdout or "", "stderr": (exc.stderr or "") + "\nTimed out", "command": cmd}


def load_native_library(path: str) -> ctypes.CDLL:
    return ctypes.CDLL(str(path))


def call_native(library_path: str, symbol: str, *args: Any, restype: str = "int", argtypes: list[str] | None = None) -> Any:
    lib = ctypes.CDLL(str(library_path))
    fn = getattr(lib, str(symbol))
    type_map = {"int": ctypes.c_int, "long": ctypes.c_long, "double": ctypes.c_double,
                "float": ctypes.c_float, "char_p": ctypes.c_char_p, "void": None, "bool": ctypes.c_bool}
    fn.restype = type_map.get(restype, ctypes.c_int)
    if argtypes:
        fn.argtypes = [type_map.get(t, ctypes.c_int) for t in argtypes]
    return fn(*args)


def http_get(url: str, timeout: int = 15) -> dict[str, Any]:
    with urllib.request.urlopen(str(url), timeout=float(timeout)) as response:
        raw = response.read()
        text = raw.decode("utf-8", "replace")
        try:
            data = json.loads(text)
        except Exception:
            data = None
        return {"status": response.status, "ok": 200 <= response.status < 300, "text": text, "json": data, "url": response.geturl()}


def http_post(url: str, body: Any = None, headers: dict[str, str] | None = None, timeout: int = 15) -> dict[str, Any]:
    data = None
    h = dict(headers or {})
    if body is not None:
        if isinstance(body, (dict, list)):
            data = json.dumps(body).encode()
            h.setdefault("Content-Type", "application/json")
        elif isinstance(body, str):
            data = body.encode()
        else:
            data = str(body).encode()
    req = urllib.request.Request(str(url), data=data, headers={str(k): str(v) for k, v in h.items()}, method="POST")
    try:
        with urllib.request.urlopen(req, timeout=float(timeout)) as response:
            raw = response.read()
            text = raw.decode("utf-8", "replace")
            try:
                parsed = json.loads(text)
            except Exception:
                parsed = None
            return {"status": response.status, "ok": 200 <= response.status < 300, "text": text, "json": parsed, "url": response.geturl()}
    except urllib.error.HTTPError as exc:
        raw = exc.read()
        text = raw.decode("utf-8", "replace")
        try:
            parsed = json.loads(text)
        except Exception:
            parsed = None
        return {"status": exc.code, "ok": False, "text": text, "json": parsed, "url": exc.geturl()}


def generate_typescript_client(base_url: str, module_name: str = "PeaModule") -> str:
    return f'''// Generated by PeaLang interop. Runtime base URL: {base_url}
export const PEA_BASE_URL = {json.dumps(base_url)};
export async function peaHealth() {{
  const r = await fetch(PEA_BASE_URL + "/health");
  return r.json();
}}
export async function peaInvoke(module: string, fn: string, args: unknown[] = []) {{
  const r = await fetch(PEA_BASE_URL + "/v1/invoke", {{
    method: "POST",
    headers: {{"Content-Type": "application/json"}},
    body: JSON.stringify({{module, function: fn, args}})
  }});
  const body = await r.json();
  if (!r.ok || !body.ok) throw new Error(body?.error?.message ?? "PeaLang invocation failed");
  return body.result;
}}
'''


def generate_java_client(base_url: str) -> str:
    return f'''// Generated by PeaLang interop. Base URL: {base_url}
public class PeaLangGeneratedClient {{
  private final String baseUrl = "{base_url}";
  public String health() throws java.io.IOException, InterruptedException {{
    var client = java.net.http.HttpClient.newHttpClient();
    var request = java.net.http.HttpRequest.newBuilder(java.net.URI.create(baseUrl + "/health")).GET().build();
    return client.send(request, java.net.http.HttpResponse.BodyHandlers.ofString()).body();
  }}
}}
'''


def generate_python_stub(module_name: str, functions: list[str]) -> str:
    lines = [f'"""Generated PeaLang Python bridge for {module_name}."""', "from pealang.embedding import PeaRuntime", "", f"def load(runtime: PeaRuntime):", f"    return runtime.load_file({module_name!r})"]
    for fn in functions:
        lines.append(f"def {fn}(module, *args):")
        lines.append(f"    return module.call({fn!r}, *args)")
    return "\n".join(lines) + "\n"


def json_rpc(url: str, method: str, params: Any = None, id: Any = 1, timeout: int = 15) -> dict[str, Any]:
    payload = {"jsonrpc": "2.0", "method": method, "params": params or {}, "id": id}
    return http_post(url, payload, timeout=timeout)


def pipe_json(command: str | list[str], input_data: Any = None, timeout: int = 30) -> dict[str, Any]:
    cmd = command if isinstance(command, list) else [command]
    stdin = json.dumps(input_data) if input_data is not None else None
    try:
        proc = subprocess.run(cmd, input=stdin, capture_output=True, text=True, timeout=timeout, check=False)
        result = {"ok": proc.returncode == 0, "returncode": proc.returncode, "stdout": proc.stdout, "stderr": proc.stderr}
        try:
            result["json"] = json.loads(proc.stdout) if proc.stdout.strip() else None
        except Exception:
            result["json"] = None
        return result
    except Exception as exc:
        return {"ok": False, "error": str(exc), "returncode": -1, "stdout": "", "stderr": str(exc)}


def env_get(name: str, default: Any = None) -> Any:
    import os
    return os.environ.get(str(name), default)



def read_text(path: str, encoding: str = "utf-8") -> str:
    return Path(path).read_text(encoding=encoding)


def write_text(path: str, content: str, encoding: str = "utf-8") -> str:
    p = Path(path); p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(str(content), encoding=encoding)
    return str(p)


def read_json_file(path: str) -> Any:
    return json.loads(Path(path).read_text(encoding='utf-8'))


def write_json_file(path: str, data: Any, indent: int = 2) -> str:
    p = Path(path); p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(data, ensure_ascii=False, indent=indent, default=str), encoding='utf-8')
    return str(p)


def glob_paths(pattern: str) -> list[str]:
    from glob import glob
    return sorted(glob(str(pattern), recursive=True))


def path_exists(path: str) -> bool:
    return Path(path).exists()


def mkdir_p(path: str) -> str:
    Path(path).mkdir(parents=True, exist_ok=True)
    return str(path)


def tempdir(prefix: str = "pealang_") -> str:
    import tempfile
    return tempfile.mkdtemp(prefix=prefix)


def basename(path: str) -> str:
    return Path(path).name


def dirname(path: str) -> str:
    return str(Path(path).parent)


def join_path(*parts: str) -> str:
    return str(Path(*[str(p) for p in parts]))


def extname(path: str) -> str:
    return Path(path).suffix


def stem(path: str) -> str:
    return Path(path).stem


def is_file(path: str) -> bool:
    return Path(path).is_file()


def is_dir(path: str) -> bool:
    return Path(path).is_dir()


def abspath(path: str) -> str:
    return str(Path(path).resolve())


def cwd() -> str:
    import os
    return os.getcwd()


def platform_info() -> dict[str, str]:
    import platform
    return {"system": platform.system(), "release": platform.release(), "python": platform.python_version(), "machine": platform.machine()}

