def sse_endpoint_source() -> str:
    """Generate Server-Sent Events endpoint boilerplate."""
    return '''// Server-Sent Events endpoint
function sseHandler(req, res) {
  res.writeHead(200, {
    "Content-Type": "text/event-stream",
    "Cache-Control": "no-cache",
    "Connection": "keep-alive",
  });
  const interval = setInterval(() => {
    res.write(`data: ${JSON.stringify({ time: Date.now() })}\\n\\n`);
  }, 1000);
  req.on("close", () => clearInterval(interval));
}
'''


def websocket_handler_source() -> str:
    """Generate WebSocket handler boilerplate."""
    return '''// WebSocket handler
const WebSocket = require("ws");
function createWebSocketServer(server) {
  const wss = new WebSocket.Server({ server });
  wss.on("connection", (ws, req) => {
    ws.on("message", (msg) => {
      try {
        const data = JSON.parse(msg);
        ws.send(JSON.stringify({ echo: data, timestamp: Date.now() }));
      } catch (e) {
        ws.send(JSON.stringify({ error: e.message }));
      }
    });
    ws.on("close", () => console.log("Client disconnected"));
  });
  return wss;
}
'''


def jwt_middleware_source() -> str:
    """Generate JWT authentication middleware."""
    return '''// JWT Authentication Middleware
function jwtMiddleware(secret) {
  return (req, res, next) => {
    const auth = req.headers.authorization || "";
    const token = auth.startsWith("Bearer ") ? auth.slice(7) : null;
    if (!token) return res.status(401).json({ error: "Missing token" });
    try {
      const parts = token.split(".");
      const payload = JSON.parse(Buffer.from(parts[1], "base64").toString());
      if (payload.exp && payload.exp < Date.now() / 1000) {
        return res.status(401).json({ error: "Token expired" });
      }
      req.user = payload;
      next();
    } catch (e) {
      return res.status(401).json({ error: "Invalid token" });
    }
  };
}
'''


def rate_limiter_source() -> str:
    """Generate rate limiter middleware."""
    return '''// Rate Limiter Middleware
function rateLimiter(maxRequests = 100, windowMs = 60000) {
  const clients = new Map();
  return (req, res, next) => {
    const ip = req.ip || req.connection.remoteAddress;
    const now = Date.now();
    if (!clients.has(ip)) clients.set(ip, []);
    const timestamps = clients.get(ip).filter(t => now - t < windowMs);
    if (timestamps.length >= maxRequests) {
      return res.status(429).json({ error: "Too many requests" });
    }
    timestamps.push(now);
    clients.set(ip, timestamps);
    next();
  };
}
'''


def api_versioning_source() -> str:
    """Generate API versioning middleware."""
    return '''// API Versioning Middleware
function versionMiddleware(versions = ["v1"]) {
  return (req, res, next) => {
    const match = req.path.match(/^\\/(v\\d+)\\//);
    const version = match ? match[1] : versions[0];
    if (!versions.includes(version)) {
      return res.status(400).json({ error: `Unsupported version: ${version}` });
    }
    req.apiVersion = version;
    next();
  };
}
'''


def build_web_sdk_namespace() -> dict[str, Any]:
    return {
        "generate_typescript_client": generate_typescript_client,
        "sse_endpoint_source": sse_endpoint_source,
        "websocket_handler_source": websocket_handler_source,
        "jwt_middleware_source": jwt_middleware_source,
        "rate_limiter_source": rate_limiter_source,
        "api_versioning_source": api_versioning_source,
    }
