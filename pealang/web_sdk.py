"""Full-stack web server and auto-typed SDK generator for PeaLang (v1.5.0).

Provides code generation for TypeScript clients from PeaLang route definitions,
and enhanced web server features (SSE, WebSockets, JWT/OAuth2 middleware,
rate limiting, API versioning).
"""

from __future__ import annotations

import json
import re
from typing import Any


# ---------------------------------------------------------------------------
# TypeScript client generator
# ---------------------------------------------------------------------------

def generate_typescript_client(routes: list[dict[str, Any]] | None = None,
                               base_url: str = "http://localhost:8000",
                               module_name: str = "PeaClient") -> str:
    """Generate a type-safe TypeScript client from PeaLang route definitions."""
    routes = routes or []
    lines = [
        f"// Generated by PeaLang v1.5.0 - Auto-typed SDK",
        f"// Base URL: {base_url}",
        "",
        "const PEA_BASE_URL = " + json.dumps(base_url) + ";",
        "",
        "async function peaFetch(path: string, options?: RequestInit): Promise<any> {",
        "  const resp = await fetch(PEA_BASE_URL + path, {",
        "    headers: { 'Content-Type': 'application/json', ...options?.headers },",
        "    ...options,",
        "  });",
        "  if (!resp.ok) throw new Error(`HTTP ${resp.status}`);",
        "  return resp.json();",
        "}",
        "",
    ]
    # Generate typed functions for each route
    for route in routes:
        method = route.get("method", "GET").upper()
        path = route.get("path", "/")
        name = route.get("name", path.strip("/").replace("/", "_").replace("-", "_") or "index")
        params = route.get("params", [])
        # Build function signature
        param_str = ", ".join(f"{p['name']}: {p.get('type', 'any')}" for p in params)
        if method == "GET":
            lines.append(f"export async function {name}({param_str}): Promise<any> {{")
            # Build query string
            if params:
                qs = " + '?' + new URLSearchParams(" + json.dumps({p["name"]: "" for p in params}) + ").toString()"
                lines.append(f"  const qs = new URLSearchParams({{ {', '.join(f'{p[chr(39)+chr(39)]}: String({p[chr(39)+chr(39)]})' for p in params)} }}).toString();")
                lines.append(f"  return peaFetch('{path}?' + qs);")
            else:
                lines.append(f"  return peaFetch('{path}');")
            lines.append("}")
            lines.append("")
        elif method in ("POST", "PUT", "PATCH"):
            body_param = "body: any" if not params else ", ".join(f"{p['name']}: {p.get('type', 'any')}" for p in params)
            lines.append(f"export async function {name}({body_param}): Promise<any> {{")
            lines.append(f"  return peaFetch('{path}', {{ method: '{method}', body: JSON.stringify({{ {', '.join(p['name'] for p in params) or 'body'} }}) }});")
            lines.append("}")
            lines.append("")
        elif method == "DELETE":
            lines.append(f"export async function {name}({param_str}): Promise<any> {{")
            lines.append(f"  return peaFetch('{path}', {{ method: 'DELETE' }});")
            lines.append("}")
            lines.append("")
    # SSE helper
    lines.append("export function peaSSE(path: string, onMessage: (data: any) => void): EventSource {")
    lines.append("  const es = new EventSource(PEA_BASE_URL + path);")
    lines.append("  es.onmessage = (e) => { try { onMessage(JSON.parse(e.data)); } catch { onMessage(e.data); } };")
    lines.append("  return es;")
    lines.append("}")
    lines.append("")
    # WebSocket helper
    lines.append("export function peaWebSocket(path: string): WebSocket {")
    lines.append("  const ws = new WebSocket(PEA_BASE_URL.replace('http', 'ws') + path);")
    lines.append("  return ws;")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


